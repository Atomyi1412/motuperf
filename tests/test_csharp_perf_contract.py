def source_text(file_name: str) -> str:
    if file_name in CORE_SHARED_FILES:
        path = CORE_SHARED_SOURCE / file_name
    elif file_name in PLATFORM_SHARED_FILES:
        path = PLATFORM_SHARED_SOURCE / file_name
    else:
        path = WPF_SOURCE / file_name
    return path.read_text(encoding="utf-8")


